import requests
import json
import base64
import os
from dotenv import load_dotenv

# Загружаем переменные из .env
load_dotenv()

# Вставь сюда свои данные из консоли Yandex Cloud
FOLDER_ID = os.getenv("FOLDER_ID")
API_KEY = os.getenv("API_KEY")


def clean_and_structure_text(raw_text):
    """
    Отправляет грязный текст в YandexGPT.
    Возвращает словарь (JSON) с чистым текстом, категорией и ключевыми словами.
    """
    url = "https://llm.api.cloud.yandex.net/foundationModels/v1/completion"
    headers = {
        "Content-Type": "application/json",
        "Authorization": f"Api-Key {API_KEY}"
    }

    # Тот самый умный промпт для нейросети
    prompt = """
        Ты профессиональный медицинский редактор и корректор. Твоя цель — сделать текст грамматически безупречным для поисковой системы.

        ГЛАВНОЕ ЗАДАНИЕ (КРИТИЧЕСКИ ВАЖНО):
        В тексте уже расшифрованы аббревиатуры, например: "бета-адреноблокатор (ББ)", "артериальная гипертензия (АГ)". 
        Они стоят в именительном падеже ("что?"). Твоя задача — изменить их окончания (ПРОСКЛОНЯТЬ), чтобы они идеально соответствовали контексту предложения.

        ПРАВИЛА СКЛОНЕНИЯ:
        1. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО удалять расшифровки или сокращать их обратно.
        2. Обязательно склоняй всю группу слов перед скобками.
           - НЕПРАВИЛЬНО: "лечение бета-адреноблокатор (ББ)"
           - ПРАВИЛЬНО: "лечение бета-адреноблокаторами (ББ)"
           - НЕПРАВИЛЬНО: "у пациентов с артериальная гипертензия (АГ)"
           - ПРАВИЛЬНО: "у пациентов с артериальной гипертензией (АГ)"

        ДОПОЛНИТЕЛЬНЫЕ ПРАВИЛА:
        3. Исправь ошибки OCR: замени '♓' на 'α', '' на '≥', склей разорванные слова.
        4. УНИЧТОЖАЙ ТАБЛИЦЫ: Переведи любые табличные данные в связный текст. Каждая строка таблицы — это отдельное утверждение.
        5. ЭКРАНИРУЙ КАВЫЧКИ: Если в тексте есть ", пиши \\".
        6. ГРАНИЦЫ: Если предложение в самом конце текста не закончено — удали его целиком.

        После обработки определи категорию ("symptom_diagnostic", "doctor_restriction", "other") и 3 ключевых слова.

        Верни ответ СТРОГО в формате JSON без лишних слов: 
        {"clean_text": "...", "category": "...", "keywords": ["...", "...", "..."]}
        """

    body = {
        "modelUri": f"gpt://{FOLDER_ID}/yandexgpt/latest",  # Используем дешевую Lite-модель
        "completionOptions": {"stream": False, "temperature": 0.1, "maxTokens": "2000"},
        "messages": [
            {"role": "system", "text": prompt},
            {"role": "user", "text": raw_text}
        ]
    }

    # Отправляем запрос
    response = requests.post(url, headers=headers, json=body)
    response.raise_for_status()

    # Извлекаем ответ нейросети
    ai_reply = response.json()['result']['alternatives'][0]['message']['text']

    # 1. Убираем внешние кавычки, пробелы и переносы
    ai_reply = ai_reply.strip('` \n')

    # 3. Заменяем только табуляции
    ai_reply = ai_reply.replace('\t', ' ')

    # 4. Парсим
    return json.loads(ai_reply, strict=False)


